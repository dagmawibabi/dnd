class CharacterPreset {
  const CharacterPreset({
    required this.name,
    required this.title,
    required this.raceId,
    this.subraceId,
    required this.classId,
    required this.backgroundId,
    required this.scores,
    required this.plus2,
    required this.plus1,
    required this.blurb,
    required this.skin,
    required this.hair,
    required this.eyes,
    this.hairStyle = 0,
    this.beard = 0,
    this.accessory = 0,
    this.feminine = 0.5,
    this.multiclass = const {},
    this.pronouns = 'he/him',
    this.personality = '',
  });

  final String name;
  final String title;
  final String raceId;
  final String? subraceId;
  final String classId;
  final String backgroundId;
  final Map<Ability, int> scores;
  final Ability plus2;
  final Ability plus1;
  final String blurb;
  final Color skin;
  final Color hair;
  final Color eyes;
  final int hairStyle;
  final int beard;
  final int accessory;
  final double feminine;
  final Map<String, int> multiclass;
  final String pronouns;
  final String personality;

  Character create() {
    final c = Character.build(
      name: name,
      title: title,
      raceId: raceId,
      subraceId: subraceId,
      classId: classId,
      backgroundId: backgroundId,
      baseScores: Map.of(scores),
      plus2: plus2,
      plus1: plus1,
      personality: personality,
      backstory: blurb,
      pronouns: pronouns,
      portrait: PortraitSpec(
        seed: name.hashCode & 0x3FFFFFFF,
        skin: skin,
        hair: hair,
        eyes: eyes,
        hairStyle: hairStyle,
        beard: beard,
        accessory: accessory,
        feminine: feminine,
        background: name.length % 6,
      ),
    );
    return c;
  }
}

